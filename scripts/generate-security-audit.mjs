import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, extname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const output = resolve(root, "src/generated/source-security-audit.ts");
const textExtensions = new Set([
  ".css",
  ".html",
  ".js",
  ".json",
  ".md",
  ".mjs",
  ".sql",
  ".ts",
  ".tsx",
]);

const excludedDirectories = new Set([
  ".git",
  ".nitro",
  ".output",
  ".vercel",
  ".vinxi",
  ".wrangler",
  "dist",
  "node_modules",
]);

function listWorkspaceFiles(directory = root) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    if (entry.isDirectory() && excludedDirectories.has(entry.name)) return [];
    const absolutePath = resolve(directory, entry.name);
    if (entry.isDirectory()) return listWorkspaceFiles(absolutePath);
    return [relative(root, absolutePath)];
  });
}

const trackedFiles = listWorkspaceFiles();

const committedSecretPatterns = [
  { id: "supabase-secret-literal", pattern: /sb_secret_[A-Za-z0-9_-]{16,}/ },
  { id: "private-key-material", pattern: /-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----/ },
  {
    id: "service-role-env-value",
    pattern: /SUPABASE_SERVICE_ROLE_KEY\s*=\s*[^\s"'<>{}]{16,}/,
  },
];
const clientExposurePatterns = [
  { id: "vite-secret-variable", pattern: /VITE_[A-Z0-9_]*(?:SECRET|PRIVATE|SERVICE_ROLE)/ },
  { id: "client-service-role-reference", pattern: /\bservice_role\b/ },
];

const committedSecretFindings = [];
const clientSecretEnvFindings = [];
let scannedFiles = 0;

for (const file of trackedFiles) {
  if (!textExtensions.has(extname(file)) && !file.startsWith(".env")) continue;
  let content;
  try {
    content = readFileSync(resolve(root, file), "utf8");
  } catch {
    continue;
  }
  scannedFiles += 1;

  for (const rule of committedSecretPatterns) {
    if (rule.pattern.test(content)) committedSecretFindings.push({ rule: rule.id, file });
  }
  if (file.startsWith("src/")) {
    for (const rule of clientExposurePatterns) {
      if (rule.pattern.test(content)) clientSecretEnvFindings.push({ rule: rule.id, file });
    }
  }
}

function serializeFindings(findings) {
  if (findings.length === 0) return "[]";
  return `[\n${findings
    .map(
      ({ rule, file }) => `    { rule: ${JSON.stringify(rule)}, file: ${JSON.stringify(file)} },`,
    )
    .join("\n")}\n  ]`;
}

mkdirSync(dirname(output), { recursive: true });
writeFileSync(
  output,
  `// Generated by scripts/generate-security-audit.mjs. Never include matched values.\nexport const SOURCE_SECURITY_AUDIT = {\n  scannedFiles: ${scannedFiles},\n  committedSecretFindings: ${serializeFindings(committedSecretFindings)},\n  clientSecretEnvFindings: ${serializeFindings(clientSecretEnvFindings)},\n} as const;\n`,
);
